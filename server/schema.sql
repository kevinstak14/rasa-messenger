PRAGMA foreign_keys = ON;
CREATE TABLE IF NOT EXISTS users (
 id INTEGER PRIMARY KEY AUTOINCREMENT, phone TEXT UNIQUE NOT NULL, name TEXT NOT NULL,
 username TEXT UNIQUE, avatar TEXT, bio TEXT DEFAULT '', online INTEGER DEFAULT 0,
 last_seen TEXT DEFAULT CURRENT_TIMESTAMP, created_at TEXT DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS chats (
 id INTEGER PRIMARY KEY AUTOINCREMENT, title TEXT, type TEXT NOT NULL DEFAULT 'private',
 created_by INTEGER, created_at TEXT DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS chat_members (
 chat_id INTEGER NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 role TEXT DEFAULT 'member', muted INTEGER DEFAULT 0, archived INTEGER DEFAULT 0,
 PRIMARY KEY(chat_id,user_id)
);
CREATE TABLE IF NOT EXISTS messages (
 id INTEGER PRIMARY KEY AUTOINCREMENT, chat_id INTEGER NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
 sender_id INTEGER NOT NULL REFERENCES users(id), body TEXT DEFAULT '', type TEXT DEFAULT 'text',
 file_url TEXT, reply_to INTEGER, forwarded_from INTEGER, edited INTEGER DEFAULT 0,
 deleted INTEGER DEFAULT 0, created_at TEXT DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_messages_chat ON messages(chat_id,id);
CREATE TABLE IF NOT EXISTS reactions (
 id INTEGER PRIMARY KEY AUTOINCREMENT, message_id INTEGER NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, emoji TEXT NOT NULL,
 UNIQUE(message_id,user_id,emoji)
);
CREATE TABLE IF NOT EXISTS reads (
 chat_id INTEGER NOT NULL, user_id INTEGER NOT NULL, last_message_id INTEGER DEFAULT 0,
 PRIMARY KEY(chat_id,user_id)
);
